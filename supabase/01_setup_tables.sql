-- Drop existing tables in correct order (respecting FK dependencies)
drop table if exists public.user_profiles cascade;
drop table if exists public.user_roles cascade;
drop table if exists public.app_roles cascade;

-- ============================================
-- app_roles: Application role definitions
-- ============================================
create table public.app_roles (
  id bigint generated by default as identity not null,
  level smallint null default '0'::smallint,
  role character varying null,
  role_display character varying null,
  constraint app_roles_pkey primary key (id),
  constraint app_roles_role_key unique (role)
) TABLESPACE pg_default;

comment on table public.app_roles is 'Application roles for the application.';

